-- na primeira execucao pode dar ORA-00942 em algum DROP, pode ignorar
DROP TABLE IntervencaoOperacional CASCADE CONSTRAINTS;
DROP TABLE RelatorioPrioridade CASCADE CONSTRAINTS;
DROP TABLE TrechoRodovia CASCADE CONSTRAINTS;
DROP TABLE EquipeManutencao CASCADE CONSTRAINTS;

CREATE TABLE EquipeManutencao (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL
);

-- tipo_clima: SECO ou UMIDO (classes TrechoSeco e TrechoUmido)
-- possui_sensor: 1 = trecho inteligente (implementa MonitoravelViaIoT), 0 = sem sensor
-- id_equipe: equipe alocada ao trecho (pode ficar vazio)
CREATE TABLE TrechoRodovia (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_rodovia VARCHAR2(50) NOT NULL,
    km_inicial NUMBER NOT NULL,
    km_final NUMBER NOT NULL,
    tipo_clima VARCHAR2(10) NOT NULL,
    possui_sensor NUMBER(1) DEFAULT 0 NOT NULL,
    nivel_vegetacao NUMBER DEFAULT 0 NOT NULL,
    id_equipe NUMBER,
    CONSTRAINT ck_trecho_km CHECK (km_inicial < km_final),
    CONSTRAINT ck_trecho_clima CHECK (tipo_clima IN ('SECO', 'UMIDO')),
    CONSTRAINT ck_trecho_sensor CHECK (possui_sensor IN (0, 1)),
    CONSTRAINT ck_trecho_vegetacao CHECK (nivel_vegetacao >= 0),
    CONSTRAINT fk_trecho_equipe FOREIGN KEY (id_equipe) REFERENCES EquipeManutencao (id)
);

-- tipo: ROCADA_MECANIZADA ou PULVERIZACAO (classes filhas de IntervencaoOperacional)
CREATE TABLE IntervencaoOperacional (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trecho NUMBER NOT NULL,
    tipo VARCHAR2(30) NOT NULL,
    CONSTRAINT ck_intervencao_tipo CHECK (tipo IN ('ROCADA_MECANIZADA', 'PULVERIZACAO')),
    CONSTRAINT fk_intervencao_trecho FOREIGN KEY (id_trecho) REFERENCES TrechoRodovia (id)
);

CREATE TABLE RelatorioPrioridade (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qt_critico NUMBER DEFAULT 0,
    qt_atencao NUMBER DEFAULT 0,
    qt_normal NUMBER DEFAULT 0,
    resumo VARCHAR2(500),
    data_geracao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
